// Generates src/abis.ts from the Foundry build output, so TypeScript code (Arena, SDK, keeper,
// web) gets fully typed contract ABIs. Run `pnpm --filter @bonded/shared abis` after changing
// a contract's interface; `abis:check` fails if the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const OUT = fileURLToPath(new URL("../../../contracts/evm/out/", import.meta.url));
const TARGET = fileURLToPath(new URL("../src/abis.ts", import.meta.url));

// Every contract in a deployment, plus the per-agent vault.
const CONTRACTS = [
  "BondedRegistry",
  "MandateVaultFactory",
  "MandateVault",
  "CoverPool",
  "OperatorBond",
  "CoverManager",
  "ClaimsEngine",
  "DisputeModule",
  "BountyBoard",
  "MockOracle",
  "TestToken",
  "DemoRouter",
];

let body =
  "// Generated by scripts/gen-abis.mjs from contracts/evm/out. Do not edit by hand.\n" +
  "// Regenerate with `pnpm --filter @bonded/shared abis` after changing a contract's interface.\n";
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(`${OUT}${name}.sol/${name}.json`, "utf8"));
  const key = name.charAt(0).toLowerCase() + name.slice(1);
  // solc lists an error twice when a contract declares it and also reverts with a shared
  // library's error of the same signature (MandateVault and MandateErrors); keep one copy.
  const seen = new Set();
  const abi = artifact.abi.filter((item) => {
    const id = JSON.stringify(item);
    if (seen.has(id)) return false;
    seen.add(id);
    return true;
  });
  body += `\nexport const ${key}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}

const options = (await prettier.resolveConfig(TARGET)) ?? {};
body = await prettier.format(body, { ...options, filepath: TARGET });

if (process.argv.includes("--check")) {
  if (readFileSync(TARGET, "utf8") !== body) {
    console.error("src/abis.ts is out of date. Run `pnpm --filter @bonded/shared abis`.");
    process.exit(1);
  }
  console.log("src/abis.ts is up to date.");
} else {
  writeFileSync(TARGET, body);
  console.log(`Wrote ${CONTRACTS.length} ABIs to src/abis.ts`);
}
