// Generates src/idls.ts from the Anchor build's IDLs, so the TypeScript client decodes accounts
// and encodes instructions exactly as the programs define them. Run `pnpm --filter
// @bonded/solana idls` after changing a program's interface (after `pnpm solana:build`);
// `idls:check` fails if the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const IDL_DIR = fileURLToPath(new URL("../../../contracts/solana/target/idl/", import.meta.url));
const TARGET = fileURLToPath(new URL("../src/idls.ts", import.meta.url));
const PROGRAMS = {
  bondedRegistry: "bonded_registry",
  bondedVault: "bonded_vault",
  bondedCover: "bonded_cover",
};

let body =
  "// Generated by scripts/gen-idls.mjs from contracts/solana/target/idl. Do not edit by hand.\n" +
  "// Regenerate with `pnpm --filter @bonded/solana idls` after changing a program's interface.\n" +
  'import type { Idl } from "@anchor-lang/core";\n';
for (const [key, file] of Object.entries(PROGRAMS)) {
  const idl = JSON.parse(readFileSync(`${IDL_DIR}${file}.json`, "utf8"));
  body += `\nexport const ${key}Idl: Idl = ${JSON.stringify(idl, null, 2)};\n`;
}
const options = (await prettier.resolveConfig(TARGET)) ?? {};
body = await prettier.format(body, { ...options, filepath: TARGET });

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(TARGET, "utf8");
  } catch {}
  if (current !== body) {
    console.error("src/idls.ts is out of date: run `pnpm --filter @bonded/solana idls`");
    process.exit(1);
  }
  console.log("src/idls.ts matches the Anchor build");
} else {
  writeFileSync(TARGET, body);
  console.log("wrote src/idls.ts");
}
